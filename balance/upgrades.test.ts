/**
 * Upgrade report: which upgrades actually help?
 * The bot plays full runs taking RANDOM picks (so rarity doesn't bias anything), and every pick is
 * recorded with when it was taken. An upgrade's score is how much further runs went after taking it,
 * compared with the average pick made in the same biome. Positive = strong, negative = weak.
 * Run with `npm run balance -- upgrades` (slow). Writes docs/upgrade-report.md.
 */
import { it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { CLASSES, type ClassId } from '../src/content/classes';
import { UPGRADES, UPGRADE_BY_ID } from '../src/content/upgrades';
import { mulberry32 } from '../src/core/rng';
import { bestAngle } from '../src/sim/bot';
import { STEP } from '../src/sim/constants';
import { Sim } from '../src/sim/world';

const RUNS = Number(process.env.RUNS ?? 50);
const CANDIDATES = Number(process.env.CANDIDATES ?? 4);
const MAX_TURNS = Number(process.env.MAX_TURNS ?? 220);

interface Pick { id: string; biome: number; depth: number; via: 'card' | 'loot' }
interface Run { classId: ClassId; depth: number; won: boolean; picks: Pick[] }

function playRun(seed: number, classId: ClassId): Run {
  const sim = new Sim(seed, { classId });
  const rnd = mulberry32(seed ^ 0xbeef);
  const picks: Pick[] = [];
  let turns = 0;
  while (sim.phase !== 'over' && sim.phase !== 'won' && turns < MAX_TURNS) {
    if (sim.phase === 'pick') {
      const ids = sim.offer!.ids;
      const i = Math.floor(rnd() * ids.length);
      picks.push({ id: ids[i], biome: sim.biome, depth: sim.level, via: 'card' });
      sim.choose(i);
      continue;
    }
    sim.fire(bestAngle(sim, CANDIDATES));
    let guard = 0;
    while (!['aim', 'pick', 'over', 'won'].includes(sim.phase) && guard++ < 240 * 60) {
      sim.tick(STEP);
      for (const e of sim.drainEvents()) if (e.type === 'loot' && e.upgrade) picks.push({ id: e.upgrade, biome: sim.biome, depth: sim.level, via: 'loot' });
    }
    if (guard >= 240 * 60) sim.recall();
    turns++;
  }
  return { classId, depth: sim.level, won: sim.won, picks };
}

const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const median = (xs: number[]) => { const s = [...xs].sort((a, b) => a - b); return s.length ? s[Math.floor(s.length / 2)] : 0; };

it('upgrade report', async () => {
  const runs: Run[] = [];
  for (let i = 0; i < RUNS; i++) {
    runs.push(playRun(20000 + i * 7919, CLASSES[i % CLASSES.length].id));
    console.log(`run ${i + 1}/${RUNS}: ${runs[i].classId} depth ${runs[i].depth}, ${runs[i].picks.length} picks`);
    await new Promise((res) => setTimeout(res, 0));
  }
  // Baseline: average remaining depth after any pick in each biome.
  const all = runs.flatMap((r) => r.picks.map((p) => ({ ...p, remaining: r.depth - p.depth })));
  const byBiome = new Map<number, number[]>();
  for (const p of all) byBiome.set(p.biome, [...(byBiome.get(p.biome) ?? []), p.remaining]);
  const expected = new Map([...byBiome].map(([b, xs]) => [b, mean(xs)]));

  const rows = UPGRADES.filter((u) => u.rarity !== 'cursed').map((u) => {
    const ps = all.filter((p) => p.id === u.id);
    const score = mean(ps.map((p) => p.remaining - (expected.get(p.biome) ?? 0)));
    const runsWith = runs.filter((r) => r.picks.some((p) => p.id === u.id));
    return { u, n: ps.length, score, depthWith: median(runsWith.map((r) => r.depth)) };
  }).sort((a, b) => b.score - a.score);

  const lines: string[] = [];
  lines.push('# Upgrade report', '');
  lines.push(`${RUNS} bot runs with **random** picks (${CANDIDATES} candidate angles per shot). Generated by \`npm run balance -- upgrades\`.`, '');
  lines.push('**Score** = how many more rows runs survived after taking the upgrade, compared with the average pick made in the same biome. Positive is strong, negative is weak. Treat anything with fewer than 6 picks as noise.', '');
  lines.push(`Overall median depth: ${median(runs.map((r) => r.depth))}. Wins: ${runs.filter((r) => r.won).length}/${RUNS}.`, '');
  lines.push('| Upgrade | Rarity | Picks | Score | Median depth of runs with it |', '|---|---|---|---|---|');
  for (const r of rows) lines.push(`| ${r.u.name} | ${r.u.rarity} | ${r.n} | ${r.n ? (r.score >= 0 ? '+' : '') + r.score.toFixed(1) : '–'} | ${r.n ? r.depthWith : '–'} |`);
  lines.push('', '## By class', '', '| Class | Median depth | Wins |', '|---|---|---|');
  for (const c of CLASSES) {
    const rs = runs.filter((r) => r.classId === c.id);
    lines.push(`| ${c.name} | ${median(rs.map((r) => r.depth))} | ${rs.filter((r) => r.won).length}/${rs.length} |`);
  }
  lines.push('');
  writeFileSync(new URL('../docs/upgrade-report.md', import.meta.url), lines.join('\n'));
  console.log(lines.join('\n'));
  void UPGRADE_BY_ID;
});
